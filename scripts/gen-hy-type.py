#!/usr/bin/env python3
"""Generate styles/lang-hy.css: a proportionally smaller type scale for Armenian.

Armenian words are long and the script is wide, so the Latin display sizes break layouts.
Every font-size declared with a rem/clamp value in styles/*.css is re-declared under
html:lang(hy) multiplied by a factor that depends on how large the original is — big
display type shrinks most, body text barely. Media-query context is preserved.
Re-run after changing type sizes:  python3 scripts/gen-hy-type.py
"""
import re
from pathlib import Path
import tinycss2

ROOT = Path(__file__).resolve().parent.parent / "styles"
SKIP = {"lang-hy.css", "tokens.css", "fonts.css"}


def min_rem(value: str) -> float:
    nums = [float(n) for n in re.findall(r"(\d*\.?\d+)rem", value)]
    return nums[0] if nums else 0.0


def factor(value: str) -> float:
    m = min_rem(value)
    if m >= 2.6:
        return 0.48
    if m >= 1.7:
        return 0.6
    if m >= 1.3:
        return 0.74
    if m >= 1.05:
        return 0.86
    return 0.94


def walk(rules, media, out):
    for rule in rules:
        if rule.type == "at-rule" and rule.lower_at_keyword == "media" and rule.content:
            q = tinycss2.serialize(rule.prelude).strip()
            walk(tinycss2.parse_rule_list(rule.content, skip_whitespace=True, skip_comments=True), media + [q], out)
        elif rule.type == "qualified-rule":
            sel = tinycss2.serialize(rule.prelude).strip()
            if "keyframes" in sel or sel.startswith(("from", "to")) or "%" in sel or ":lang(" in sel:
                continue
            for d in tinycss2.parse_declaration_list(rule.content, skip_whitespace=True, skip_comments=True):
                if d.type != "declaration" or d.lower_name != "font-size":
                    continue
                v = tinycss2.serialize(d.value).strip()
                if "rem" not in v or "var(" in v and "rem" not in v.split("var(")[0]:
                    continue
                f = factor(v)
                if f >= 0.94 and min_rem(v) < 1.05 and "clamp" not in v:
                    continue
                sels = ", ".join(f"html:lang(hy) {s.strip()}" for s in sel.split(","))
                out.append((tuple(media), f"{sels} {{\n  font-size: calc({v} * {f});\n}}"))


out = []
for css in sorted(ROOT.glob("*.css")):
    if css.name in SKIP:
        continue
    rules = tinycss2.parse_stylesheet(css.read_text(), skip_whitespace=True, skip_comments=True)
    walk(rules, [], out)

lines = ["/* GENERATED by scripts/gen-hy-type.py — Armenian type scale. Do not edit by hand. */", "",
         "html:lang(hy) {",
         "  --fs-giant: calc(clamp(3.4rem, 0.6rem + 9.4vw, 11rem) * 0.48);",
         "  --fs-display: calc(clamp(2.9rem, 0.9rem + 6.2vw, 7.4rem) * 0.48);",
         "  --fs-h1: calc(clamp(2.6rem, 1.1rem + 4.6vw, 6rem) * 0.55);",
         "  --fs-h2: calc(clamp(2.15rem, 1.15rem + 3.1vw, 4.4rem) * 0.6);",
         "  --fs-h3: calc(clamp(1.55rem, 1rem + 1.6vw, 2.6rem) * 0.74);",
         "  --fs-h4: calc(clamp(1.2rem, 1rem + 0.6vw, 1.55rem) * 0.86);",
         "  --fs-lead: calc(clamp(1.06rem, 0.98rem + 0.32vw, 1.3rem) * 0.9);",
         "  --fs-body: 0.94rem;",
         "  --fs-small: 0.82rem;",
         "  --fs-xs: 0.76rem;",
         "  --fs-label: 0.76rem;",
         "  --fs-mono: 0.72rem;",
         "}", "",
         "html:lang(hy) body {", "  font-size: 0.94rem;", "}", ""]
for media, block in out:
    if media:
        inner = "\n".join("  " + l for l in block.splitlines())
        for q in reversed(media):
            inner = f"@media {q} {{\n{inner}\n}}"
            # nested media are rare; keep simple
        lines.append(inner)
    else:
        lines.append(block)
    lines.append("")
(ROOT / "lang-hy.css").write_text("\n".join(lines))
print(len(out), "rules")
